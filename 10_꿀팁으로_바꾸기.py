def run(*a, check=False):
    r = subprocess.run(a, cwd=HERE, capture_output=True, text=True, encoding="utf-8")
    if check and r.returncode != 0:
        print(r.stdout, r.stderr)
        sys.exit(f"실패: {' '.join(a)}")
    return r


