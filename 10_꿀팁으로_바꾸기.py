with open(QUEUE, encoding="utf-8-sig", newline="") as f:
    rows = list(csv.DictReader(f))
skipped = 0
for r in rows:
    if r.get("status", "").strip().lower() not in ("done", "error", "skip") \
            and r["caption"] not in {n["caption"] for n in NEW_ROWS}:
        r["status"] = "skip"
        r["result"] = "꿀팁 계정 전환으로 취소"
        skipped += 1
done_caps = {r["caption"] for r in rows if r.get("status", "").strip().lower() == "done"}
have_caps = {r["caption"] for r in rows}
added = 0
for n in NEW_ROWS:
    # 짧은 이전 버전이 이미 올라갔으면 같은 꿀팁을 또 올리지 않는다
    if n["old"] in done_caps or n["caption"] in have_caps:
        continue
    rows.append({k: n[k] for k in FIELDS})
    added += 1
with open(QUEUE, "w", encoding="utf-8-sig", newline="") as f:
    w = csv.DictWriter(f, fieldnames=FIELDS)
    w.writeheader()
    for r in rows:
        w.writerow({k: r.get(k, "") for k in FIELDS})
print(f"   예약 글 {skipped}개 취소, 꿀팁 글 {added}개 예약")

